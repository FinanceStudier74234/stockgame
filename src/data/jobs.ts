export function getJobById(id: string): Job | undefined {
  return JOBS.find(j => j.id === id);
}

export function getJobsByTier(tier: string): Job[] {
  return JOBS.filter(j => j.tier === tier);
}

export function getAvailableJobs(playerSkills: Record<string, number>, playerStats: Record<string, number>, unlockedMechanics: string[]): Job[] {
  return JOBS.filter(job => {
    if (job.unlockCondition && !unlockedMechanics.includes(job.unlockCondition)) return false;
    const skillsMet = Object.entries(job.skillRequirements).every(
      ([skill, req]) => (playerSkills[skill] || 0) >= (req as number)
    );
    const statsMet = Object.entries(job.statRequirements).every(
      ([stat, req]) => (playerStats[stat] || 0) >= (req as number)
    );
    return skillsMet && statsMet;
  });
}
