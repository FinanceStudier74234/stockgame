// Helper to generate initial price history
function generatePriceHistory(price: number, volatility: number, days: number = 30): number[] {
  const history: number[] = [];
  let p = price * (0.7 + Math.random() * 0.3);
  for (let i = 0; i < days; i++) {
    const change = (Math.random() - 0.48) * volatility * p;
    p = Math.max(p + change, 0.01);
    history.push(parseFloat(p.toFixed(2)));
  }
  history.push(price);
  return history;
}

